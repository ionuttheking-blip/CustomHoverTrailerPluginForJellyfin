using System.Text.Json;
using TrailerGenerator.WinForms.Models;

namespace TrailerGenerator.WinForms.Services;

/// <summary>
/// Data model representing the persisted application state.
/// </summary>
public class AppStateModel
{
    public List<string> Folders { get; set; } = new();
    public List<SavedVideoEntry> Videos { get; set; } = new();
    public int GenerationMode { get; set; } = 0;
    public bool UseStartPercentage { get; set; } = true;
    public double StartPercentage { get; set; } = 10.0;
    public double FixedStartSeconds { get; set; } = 120.0;
    public double EndSkipPercentage { get; set; } = 10.0;
    public int TargetDurationSeconds { get; set; } = 60;
    public int SnippetCount { get; set; } = 6;
    public int MaxParallelCount { get; set; } = 2;
    public string ResolutionScale { get; set; } = "1280:-2";
    public bool IncludeAudio { get; set; } = true;
    public bool SmoothFadeTransitions { get; set; } = true;
    public bool OverwriteExisting { get; set; } = false;
    public bool UseSceneChangeDetection { get; set; } = false;
    public bool OverrideManualWithAuto { get; set; } = false;
    public bool EnableFolderWatcher { get; set; } = false;
    public bool AutoGenerateOnNewVideo { get; set; } = false;
    public int AutoGenerateDelaySeconds { get; set; } = 15;
    public int DefaultPreviewVolume { get; set; } = 50;
}

/// <summary>
/// Persisted state entry for a scanned video.
/// </summary>
public class SavedVideoEntry
{
    public string VideoPath { get; set; } = string.Empty;
    public bool IsSelected { get; set; } = true;
    public bool WasGenerated { get; set; } = false;
    public string StatusMessage { get; set; } = string.Empty;
    public bool IsManual { get; set; } = false;
    public List<ManualSegmentItem> ManualSegments { get; set; } = new();
    public SavedTimelineAnalysis? CachedAnalysis { get; set; }
    public List<SavedConfigurationItem> SavedConfigurations { get; set; } = new();
}

/// <summary>
/// Serializable configuration item mapping a configuration key to its segment list.
/// </summary>
public class SavedConfigurationItem
{
    public string ConfigKey { get; set; } = string.Empty;
    public List<ManualSegmentItem> Segments { get; set; } = new();
}

/// <summary>
/// Serializable cache representation of a VideoTimelineAnalysisResult.
/// </summary>
public class SavedTimelineAnalysis
{
    public double DurationSeconds { get; set; }
    public double UsableStartSeconds { get; set; }
    public double UsableEndSeconds { get; set; }
    public List<double> SceneCutTimestamps { get; set; } = new();
    public List<double> SceneStarts { get; set; } = new();
    public List<double> SceneEnds { get; set; } = new();
    public List<ManualSegmentItem> AudioModeSegments { get; set; } = new();
    public List<ManualSegmentItem> MovementModeSegments { get; set; } = new();
    public List<ManualSegmentItem> RandomModeSegments { get; set; } = new();
}

/// <summary>
/// Service responsible for persisting and restoring the application state to/from a local JSON file.
/// </summary>
public class AppStatePersistenceService
{
    private static readonly object _fileLock = new();
    private readonly string _filePath;

    public AppStatePersistenceService(string? filePath = null)
    {
        _filePath = filePath ?? Path.Combine(AppContext.BaseDirectory, "trailer-generator-state.json");
    }

    public string FilePath => _filePath;

    /// <summary>
    /// Thread-safe method to save the application state to disk.
    /// </summary>
    public void SaveState(AppStateModel state)
    {
        lock (_fileLock)
        {
            try
            {
                var options = new JsonSerializerOptions { WriteIndented = true };
                var json = JsonSerializer.Serialize(state, options);
                File.WriteAllText(_filePath, json);
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"Failed to save app state: {ex.Message}");
            }
        }
    }

    /// <summary>
    /// Thread-safe method to load the application state from disk.
    /// Returns null if file does not exist or if an error occurs.
    /// </summary>
    public AppStateModel? LoadState()
    {
        lock (_fileLock)
        {
            try
            {
                if (!File.Exists(_filePath))
                {
                    return null;
                }

                var json = File.ReadAllText(_filePath);
                return JsonSerializer.Deserialize<AppStateModel>(json);
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"Failed to load app state: {ex.Message}");
                return null;
            }
        }
    }

    /// <summary>
    /// Converts a <see cref="VideoTimelineAnalysisResult"/> to a serializable <see cref="SavedTimelineAnalysis"/>.
    /// </summary>
    public static SavedTimelineAnalysis? ToSavedTimelineAnalysis(VideoTimelineAnalysisResult? result)
    {
        if (result == null)
        {
            return null;
        }

        var saved = new SavedTimelineAnalysis
        {
            DurationSeconds = result.DurationSeconds,
            UsableStartSeconds = result.UsableStartSeconds,
            UsableEndSeconds = result.UsableEndSeconds,
            SceneCutTimestamps = result.SceneCutTimestamps != null ? new List<double>(result.SceneCutTimestamps) : new List<double>(),
            AudioModeSegments = result.AudioModeSegments?.Select(s => s.Clone()).ToList() ?? new List<ManualSegmentItem>(),
            MovementModeSegments = result.MovementModeSegments?.Select(s => s.Clone()).ToList() ?? new List<ManualSegmentItem>(),
            RandomModeSegments = result.RandomModeSegments?.Select(s => s.Clone()).ToList() ?? new List<ManualSegmentItem>()
        };

        if (result.Scenes != null)
        {
            foreach (var scene in result.Scenes)
            {
                saved.SceneStarts.Add(scene.SceneStart);
                saved.SceneEnds.Add(scene.SceneEnd);
            }
        }

        return saved;
    }

    /// <summary>
    /// Converts a <see cref="SavedTimelineAnalysis"/> back to a runtime <see cref="VideoTimelineAnalysisResult"/>.
    /// </summary>
    public static VideoTimelineAnalysisResult? ToVideoTimelineAnalysisResult(SavedTimelineAnalysis? saved)
    {
        if (saved == null)
        {
            return null;
        }

        var result = new VideoTimelineAnalysisResult
        {
            DurationSeconds = saved.DurationSeconds,
            UsableStartSeconds = saved.UsableStartSeconds,
            UsableEndSeconds = saved.UsableEndSeconds,
            SceneCutTimestamps = saved.SceneCutTimestamps != null ? new List<double>(saved.SceneCutTimestamps) : new List<double>(),
            AudioModeSegments = saved.AudioModeSegments?.Select(s => s.Clone()).ToList() ?? new List<ManualSegmentItem>(),
            MovementModeSegments = saved.MovementModeSegments?.Select(s => s.Clone()).ToList() ?? new List<ManualSegmentItem>(),
            RandomModeSegments = saved.RandomModeSegments?.Select(s => s.Clone()).ToList() ?? new List<ManualSegmentItem>()
        };

        if (saved.SceneStarts != null && saved.SceneEnds != null)
        {
            int count = Math.Min(saved.SceneStarts.Count, saved.SceneEnds.Count);
            for (int i = 0; i < count; i++)
            {
                result.Scenes.Add((saved.SceneStarts[i], saved.SceneEnds[i]));
            }
        }

        return result;
    }

    /// <summary>
    /// Converts a dictionary of configuration items to a serializable list.
    /// </summary>
    public static List<SavedConfigurationItem> ToSavedConfigurations(Dictionary<string, List<ManualSegmentItem>>? configurations)
    {
        if (configurations == null || configurations.Count == 0)
        {
            return new List<SavedConfigurationItem>();
        }

        var list = new List<SavedConfigurationItem>(configurations.Count);
        foreach (var kvp in configurations)
        {
            list.Add(new SavedConfigurationItem
            {
                ConfigKey = kvp.Key,
                Segments = kvp.Value?.Select(s => s.Clone()).ToList() ?? new List<ManualSegmentItem>()
            });
        }
        return list;
    }

    /// <summary>
    /// Converts a serializable list of configurations back into a lookup dictionary.
    /// </summary>
    public static Dictionary<string, List<ManualSegmentItem>> ToConfigurationsDictionary(List<SavedConfigurationItem>? savedItems)
    {
        var dict = new Dictionary<string, List<ManualSegmentItem>>(StringComparer.OrdinalIgnoreCase);
        if (savedItems == null || savedItems.Count == 0)
        {
            return dict;
        }

        foreach (var item in savedItems)
        {
            if (!string.IsNullOrWhiteSpace(item.ConfigKey))
            {
                dict[item.ConfigKey] = item.Segments?.Select(s => s.Clone()).ToList() ?? new List<ManualSegmentItem>();
            }
        }
        return dict;
    }
}

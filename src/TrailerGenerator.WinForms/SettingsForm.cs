using TrailerGenerator.WinForms.Services;

namespace TrailerGenerator.WinForms;

/// <summary>
/// Modal dialog for configuring application-wide settings and the background folder watcher engine.
/// </summary>
public sealed class SettingsForm : Form
{
    private readonly CheckBox _enableFolderWatcherCheckBox = new();
    private readonly CheckBox _autoGenOnNewVideoCheckBox = new();
    private readonly NumericUpDown _autoGenDelayNumeric = new();
    private readonly NumericUpDown _defaultVolumeNumeric = new();
    private readonly Button _btnOk = new();
    private readonly Button _btnCancel = new();

    public SettingsForm(AppStateModel state)
    {
        ArgumentNullException.ThrowIfNull(state);

        Text = "Application & Auto-Watcher Settings";
        StartPosition = FormStartPosition.CenterParent;
        Width = 520;
        Height = 440;
        FormBorderStyle = FormBorderStyle.FixedDialog;
        MaximizeBox = false;
        MinimizeBox = false;
        ShowInTaskbar = false;
        Font = new Font("Segoe UI", 9.5F);

        InitializeLayout(state);
    }

    private void InitializeLayout(AppStateModel state)
    {
        var mainLayout = new TableLayoutPanel
        {
            Dock = DockStyle.Fill,
            ColumnCount = 1,
            RowCount = 3,
            Padding = new Padding(14)
        };
        mainLayout.RowStyles.Add(new RowStyle(SizeType.Absolute, 200)); // Watcher group
        mainLayout.RowStyles.Add(new RowStyle(SizeType.Absolute, 110)); // Editor group
        mainLayout.RowStyles.Add(new RowStyle(SizeType.Percent, 100));  // Buttons

        // 1. Folder Monitoring Group
        var watcherGroup = new GroupBox
        {
            Text = "Library Folder Monitoring & Auto-Generation",
            Dock = DockStyle.Fill,
            Padding = new Padding(12)
        };

        var watcherLayout = new TableLayoutPanel
        {
            Dock = DockStyle.Fill,
            ColumnCount = 2,
            RowCount = 3
        };
        watcherLayout.ColumnStyles.Add(new ColumnStyle(SizeType.Percent, 72));
        watcherLayout.ColumnStyles.Add(new ColumnStyle(SizeType.Percent, 28));
        watcherLayout.RowStyles.Add(new RowStyle(SizeType.Absolute, 38));
        watcherLayout.RowStyles.Add(new RowStyle(SizeType.Absolute, 38));
        watcherLayout.RowStyles.Add(new RowStyle(SizeType.Absolute, 45));

        _enableFolderWatcherCheckBox.Text = "Enable Folder Watcher (Monitor folders for new videos)";
        _enableFolderWatcherCheckBox.AutoSize = true;
        _enableFolderWatcherCheckBox.Checked = state.EnableFolderWatcher;
        _enableFolderWatcherCheckBox.Dock = DockStyle.Fill;

        _autoGenOnNewVideoCheckBox.Text = "Automatically generate trailers when new videos appear";
        _autoGenOnNewVideoCheckBox.AutoSize = true;
        _autoGenOnNewVideoCheckBox.Checked = state.AutoGenerateOnNewVideo;
        _autoGenOnNewVideoCheckBox.Dock = DockStyle.Fill;

        var delayLabel = new Label
        {
            Text = "Debounce Delay Before Auto-Generation (seconds):",
            AutoSize = true,
            Dock = DockStyle.Fill,
            TextAlign = ContentAlignment.MiddleLeft
        };

        _autoGenDelayNumeric.Minimum = 5;
        _autoGenDelayNumeric.Maximum = 300;
        _autoGenDelayNumeric.Value = Math.Clamp(state.AutoGenerateDelaySeconds, 5, 300);
        _autoGenDelayNumeric.Width = 85;
        _autoGenDelayNumeric.Anchor = AnchorStyles.Left;

        _enableFolderWatcherCheckBox.CheckedChanged += (_, _) => UpdateWatcherControlsState();

        watcherLayout.Controls.Add(_enableFolderWatcherCheckBox, 0, 0);
        watcherLayout.SetColumnSpan(_enableFolderWatcherCheckBox, 2);
        watcherLayout.Controls.Add(_autoGenOnNewVideoCheckBox, 0, 1);
        watcherLayout.SetColumnSpan(_autoGenOnNewVideoCheckBox, 2);
        watcherLayout.Controls.Add(delayLabel, 0, 2);
        watcherLayout.Controls.Add(_autoGenDelayNumeric, 1, 2);
        watcherGroup.Controls.Add(watcherLayout);

        // 2. Editor & Preview Defaults Group
        var editorGroup = new GroupBox
        {
            Text = "Editor & Preview Defaults",
            Dock = DockStyle.Fill,
            Padding = new Padding(12)
        };

        var editorLayout = new TableLayoutPanel
        {
            Dock = DockStyle.Fill,
            ColumnCount = 2,
            RowCount = 1
        };
        editorLayout.ColumnStyles.Add(new ColumnStyle(SizeType.Percent, 72));
        editorLayout.ColumnStyles.Add(new ColumnStyle(SizeType.Percent, 28));

        var volumeLabel = new Label
        {
            Text = "Default Preview Volume (%):",
            AutoSize = true,
            Dock = DockStyle.Fill,
            TextAlign = ContentAlignment.MiddleLeft
        };

        _defaultVolumeNumeric.Minimum = 0;
        _defaultVolumeNumeric.Maximum = 100;
        _defaultVolumeNumeric.Value = Math.Clamp(state.DefaultPreviewVolume, 0, 100);
        _defaultVolumeNumeric.Width = 85;
        _defaultVolumeNumeric.Anchor = AnchorStyles.Left;

        editorLayout.Controls.Add(volumeLabel, 0, 0);
        editorLayout.Controls.Add(_defaultVolumeNumeric, 1, 0);
        editorGroup.Controls.Add(editorLayout);

        // 3. Button Bar
        var buttonPanel = new FlowLayoutPanel
        {
            Dock = DockStyle.Fill,
            FlowDirection = FlowDirection.RightToLeft,
            Padding = new Padding(0, 10, 0, 0)
        };

        _btnCancel.Text = "Cancel";
        _btnCancel.DialogResult = DialogResult.Cancel;
        _btnCancel.Width = 95;
        _btnCancel.Height = 32;

        _btnOk.Text = "Save Settings";
        _btnOk.DialogResult = DialogResult.OK;
        _btnOk.Width = 115;
        _btnOk.Height = 32;
        _btnOk.Font = new Font(Font, FontStyle.Bold);

        buttonPanel.Controls.Add(_btnCancel);
        buttonPanel.Controls.Add(_btnOk);

        AcceptButton = _btnOk;
        CancelButton = _btnCancel;

        mainLayout.Controls.Add(watcherGroup, 0, 0);
        mainLayout.Controls.Add(editorGroup, 0, 1);
        mainLayout.Controls.Add(buttonPanel, 0, 2);

        Controls.Add(mainLayout);

        UpdateWatcherControlsState();
    }

    private void UpdateWatcherControlsState()
    {
        bool watcherEnabled = _enableFolderWatcherCheckBox.Checked;
        _autoGenOnNewVideoCheckBox.Enabled = watcherEnabled;
        _autoGenDelayNumeric.Enabled = watcherEnabled;
    }

    /// <summary>
    /// Copies control values back into the provided application state model.
    /// </summary>
    public void ApplyTo(AppStateModel state)
    {
        ArgumentNullException.ThrowIfNull(state);

        state.EnableFolderWatcher = _enableFolderWatcherCheckBox.Checked;
        state.AutoGenerateOnNewVideo = _autoGenOnNewVideoCheckBox.Checked;
        state.AutoGenerateDelaySeconds = (int)_autoGenDelayNumeric.Value;
        state.DefaultPreviewVolume = (int)_defaultVolumeNumeric.Value;
    }
}

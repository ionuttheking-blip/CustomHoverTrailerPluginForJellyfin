using System.ComponentModel;
using System.Runtime.CompilerServices;
using TrailerGenerator.WinForms.Services;

namespace TrailerGenerator.WinForms.Models;

/// <summary>
/// Represents a discovered video file and its associated local trailer status.
/// Implements <see cref="INotifyPropertyChanged"/> for real-time UI data binding.
/// </summary>
public sealed class VideoEntry : INotifyPropertyChanged
{
    private string _videoPath = string.Empty;
    private bool _isSelected = true;
    private bool _hasTrailer;
    private bool _wasGenerated;
    private string _statusMessage = "Pending";
    private bool _isManual;
    private VideoTimelineAnalysisResult? _cachedAnalysis;

    public event PropertyChangedEventHandler? PropertyChanged;

    /// <summary>
    /// Gets or sets the full path to the source video file.
    /// </summary>
    public string VideoPath
    {
        get => _videoPath;
        set
        {
            if (_videoPath != value)
            {
                _videoPath = value;
                OnPropertyChanged();
                OnPropertyChanged(nameof(FileName));
                OnPropertyChanged(nameof(FolderPath));
                OnPropertyChanged(nameof(TrailerPath));
                OnPropertyChanged(nameof(ExpectedTrailerPath));
                OnPropertyChanged(nameof(TrailerFileName));
                OnPropertyChanged(nameof(ExpectedTrailerFileName));
            }
        }
    }

    /// <summary>
    /// Gets the file name of the source video.
    /// </summary>
    public string FileName => Path.GetFileName(VideoPath);

    /// <summary>
    /// Gets the directory containing the source video.
    /// </summary>
    public string FolderPath => Path.GetDirectoryName(VideoPath) ?? string.Empty;

    /// <summary>
    /// Gets the expected output trailer path in the exact same folder: *name_of_video*-trailer.mp4.
    /// </summary>
    public string TrailerPath
    {
        get
        {
            var dir = Path.GetDirectoryName(VideoPath) ?? string.Empty;
            var nameWithoutExt = Path.GetFileNameWithoutExtension(VideoPath);
            return Path.Combine(dir, $"{nameWithoutExt}-trailer.mp4");
        }
    }

    /// <summary>
    /// Backward-compatible alias for <see cref="TrailerPath"/>.
    /// </summary>
    public string ExpectedTrailerPath => TrailerPath;

    /// <summary>
    /// Gets the expected trailer file name.
    /// </summary>
    public string TrailerFileName => Path.GetFileName(TrailerPath);

    /// <summary>
    /// Backward-compatible alias for <see cref="TrailerFileName"/>.
    /// </summary>
    public string ExpectedTrailerFileName => TrailerFileName;

    /// <summary>
    /// Gets or sets whether the trailer file already exists on disk.
    /// </summary>
    public bool HasTrailer
    {
        get => _hasTrailer;
        set
        {
            if (_hasTrailer != value)
            {
                _hasTrailer = value;
                OnPropertyChanged();
                OnPropertyChanged(nameof(HasExistingTrailer));
            }
        }
    }

    /// <summary>
    /// Backward-compatible alias for <see cref="HasTrailer"/>.
    /// </summary>
    public bool HasExistingTrailer
    {
        get => HasTrailer;
        set => HasTrailer = value;
    }

    /// <summary>
    /// Gets or sets whether the trailer was generated by the tool or already existed.
    /// </summary>
    public bool WasGenerated
    {
        get => _wasGenerated;
        set
        {
            if (_wasGenerated != value)
            {
                _wasGenerated = value;
                OnPropertyChanged();
            }
        }
    }

    /// <summary>
    /// Gets or sets whether this video is selected for trailer generation.
    /// </summary>
    public bool IsSelected
    {
        get => _isSelected;
        set
        {
            if (_isSelected != value)
            {
                _isSelected = value;
                OnPropertyChanged();
                OnPropertyChanged(nameof(Selected));
            }
        }
    }

    /// <summary>
    /// Backward-compatible alias for <see cref="IsSelected"/>.
    /// </summary>
    public bool Selected
    {
        get => IsSelected;
        set => IsSelected = value;
    }

    /// <summary>
    /// Gets or sets the current processing status text.
    /// </summary>
    public string StatusMessage
    {
        get => _statusMessage;
        set
        {
            if (_statusMessage != value)
            {
                _statusMessage = value;
                OnPropertyChanged();
                OnPropertyChanged(nameof(Status));
            }
        }
    }

    /// <summary>
    /// Backward-compatible alias for <see cref="StatusMessage"/>.
    /// </summary>
    public string Status
    {
        get => StatusMessage;
        set => StatusMessage = value;
    }

    /// <summary>
    /// Gets or sets whether this video uses manually configured segments instead of automatic detection.
    /// </summary>
    public bool IsManual
    {
        get => _isManual;
        set
        {
            if (_isManual != value)
            {
                _isManual = value;
                OnPropertyChanged();
                OnPropertyChanged(nameof(GenerationType));
            }
        }
    }

    /// <summary>
    /// Gets the display name for the generation mode ("Manual" or "Automatic").
    /// </summary>
    public string GenerationType => IsManual ? "Manual" : "Automatic";

    /// <summary>
    /// Gets or sets the manually defined segments for trailer generation.
    /// </summary>
    public List<ManualSegmentItem> ManualSegments { get; set; } = new();

    /// <summary>
    /// Gets or sets the cached timeline analysis result (scenes, cuts, audio/movement candidates)
    /// to avoid expensive FFmpeg re-analysis.
    /// </summary>
    public VideoTimelineAnalysisResult? CachedAnalysis
    {
        get => _cachedAnalysis;
        set
        {
            if (!ReferenceEquals(_cachedAnalysis, value))
            {
                _cachedAnalysis = value;
                OnPropertyChanged();
                OnPropertyChanged(nameof(AnalysisStatus));
            }
        }
    }

    /// <summary>
    /// Gets or sets saved configuration segments keyed by mode and duration (e.g., "SoundDetect_60s", "Movement_90s").
    /// </summary>
    public Dictionary<string, List<ManualSegmentItem>> SavedConfigurations { get; set; } = new(StringComparer.OrdinalIgnoreCase);

    /// <summary>
    /// Gets a readable description of which analyses (Scenes, Audio, Motion) and presets exist for this video.
    /// </summary>
    public string AnalysisStatus
    {
        get
        {
            if (CachedAnalysis == null)
            {
                if (SavedConfigurations != null && SavedConfigurations.Count > 0)
                {
                    return $"Presets Only ({SavedConfigurations.Count})";
                }
                return "Not Analyzed";
            }

            var parts = new List<string>(3);
            if (CachedAnalysis.Scenes.Count > 0 || CachedAnalysis.SceneCutTimestamps.Count > 0)
            {
                parts.Add("Scenes");
            }
            if ((CachedAnalysis.AudioPoints != null && CachedAnalysis.AudioPoints.Count > 0) || CachedAnalysis.AudioModeSegments.Count > 0)
            {
                parts.Add("Audio");
            }
            if ((CachedAnalysis.MotionPoints != null && CachedAnalysis.MotionPoints.Count > 0) || CachedAnalysis.MovementModeSegments.Count > 0)
            {
                parts.Add("Motion");
            }

            if (parts.Count == 0)
            {
                return "Partial (Metadata)";
            }

            string baseStr = parts.Count == 3 ? "Full (Scenes, Audio, Motion)" : string.Join(", ", parts);
            if (SavedConfigurations != null && SavedConfigurations.Count > 0)
            {
                var configKeys = string.Join(", ", SavedConfigurations.Keys);
                return $"{baseStr} | Configs: {configKeys}";
            }
            return baseStr;
        }
    }

    /// <summary>
    /// Explicitly notifies bindings that status and trailer properties have updated.
    /// </summary>
    public void NotifyStatusChanged()
    {
        OnPropertyChanged(nameof(StatusMessage));
        OnPropertyChanged(nameof(Status));
        OnPropertyChanged(nameof(HasTrailer));
        OnPropertyChanged(nameof(HasExistingTrailer));
        OnPropertyChanged(nameof(WasGenerated));
        OnPropertyChanged(nameof(IsSelected));
        OnPropertyChanged(nameof(Selected));
        OnPropertyChanged(nameof(IsManual));
        OnPropertyChanged(nameof(GenerationType));
        OnPropertyChanged(nameof(AnalysisStatus));
    }

    private void OnPropertyChanged([CallerMemberName] string? propertyName = null)
    {
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(propertyName));
    }
}
